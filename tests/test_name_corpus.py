"""Distinguished names: §7.1 matching, RFC 4514 rendering, and a shape no shipped root contains.

The expected renderings below come from `cryptography`, run over the three fixtures on
2026-11-05 - a second implementation, not this one's own output, for the same reason the OID and
SPKI expectations were frozen that way. Everything else here is derived from the text of RFC 5280
§7.1, RFC 4518 §2.6.1 and RFC 4514 §3, including the RFC's own worked example for insignificant
space handling.

`multivalue-rdn.der` is generated by `sdk-forge/probe_name_fixture.py`, not issued by anyone: the
store contains 577 RDNs and every one is single-valued, so multi-valued RDNs - and PrintableString
at all, which appears nowhere in it - have to be synthesised to be tested at all. Its digest is
deliberately not pinned, because the generator makes a fresh key each run; what is pinned is the
name.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from asn1core import (
    Attribute,
    CertificateError,
    Name,
    decode,
    issuer,
    names_equal,
    normalize_value,
    parse_name,
    subject,
    within,
)

FIXTURES = Path(__file__).parent / "fixtures"

RENDERINGS = {
    "root-ecdsa.der": r"CN=DigiCert CS ECC P384 Root G5,O=DigiCert\, Inc.,C=US",
    "root-rsa.der": r"OU=Class 3 Public Primary Certification Authority,O=VeriSign\, Inc.,C=US",
    "multivalue-rdn.der": (
        "1.2.840.113549.1.9.1=pki@example.test,DC=example,CN=Multi Valued Root CA #1,"
        "ST=Île-de-France,L=\\  Paris \\ ,OU=Test Services,C=FR+O=Example  Université  S.A."
    ),
}


@pytest.fixture(params=sorted(RENDERINGS))
def fixture(request: pytest.FixtureRequest) -> tuple[str, bytes]:
    name = str(request.param)
    path = FIXTURES / name
    if not path.is_file():  # pragma: no cover
        pytest.fail(f"{path} is missing; run sdk-forge/probe_name_fixture.py for the synthetic one")
    return name, path.read_bytes()


def test_renderings_match_an_independent_implementation(fixture: tuple[str, bytes]) -> None:
    name, der = fixture
    assert subject(der).rfc4514() == RENDERINGS[name], name
    assert str(subject(der)) == RENDERINGS[name], name


def test_these_are_self_signed_so_issuer_and_subject_match(
    fixture: tuple[str, bytes],
) -> None:
    name, der = fixture
    assert names_equal(issuer(der), subject(der)), name
    assert issuer(der).raw in der, name
    assert subject(der).raw in der, f"{name}: the stored bytes, not a re-encoding"


def test_the_multi_valued_rdn_is_a_set_of_attributes_not_one_attribute_per_rdn() -> None:
    """The case the trust store never exercises, so the fixture exists.

    An implementation that treats an RDN as "the attribute at index 0" silently drops the second
    attribute of a name, which turns `C=FR+O=Example` into `C=FR`: a different, shorter name that
    matches more of the tree than it should.
    """
    der = (FIXTURES / "multivalue-rdn.der").read_bytes()
    dn = subject(der)
    assert [len(rdn) for rdn in dn.rdnsets] == [2, 1, 1, 1, 1, 1, 1]
    root = dn.rdnsets[0]
    assert {(attr.short_name, attr.value) for attr in root} == {
        ("C", "FR"),
        ("O", "Example  Université  S.A."),
    }
    assert {attr.kind for attr in root} == {"printableString", "utf8String"}
    # Measured, and re-measured against X.680 (02/2021) Table 1 on 2026-11-07. `C=FR` arrives under tag 19,
    # which is PrintableString - the tag 520 of the trust store's 577 attribute values use, and the tag
    # cryptography emits for `C=US`. An earlier revision of this test read that tag as TeletexString,
    # because name.py's table was numbered four places low; the text was identical either way, since both
    # decode ASCII to the same characters, so only `kind` was wrong. §7.1 makes PrintableString and
    # UTF8String the two types a conforming implementation MUST support, and this fixture carries both.
    assert {attr.kind for rdn in dn.rdnsets for attr in rdn} == {
        "printableString",
        "utf8String",
        "ia5String",
    }
    assert dn.common_name == "Multi Valued Root CA #1"
    assert dn.values("2.5.4.6") == ("FR",)


def test_every_string_type_the_profile_names_decodes_by_its_own_codec() -> None:
    """UTF8String and PrintableString MUST be supported; BMP and Universal are optional but real.

    Each type's codec is fixed by the type, not guessed: BMPString is UTF-16BE and UniversalString
    UTF-32BE. TeletexString is the one that cannot be pinned - X.500 says T.61 and issuers have
    shipped Latin-1 and UTF-8 under the same tag - so non-UTF-8 bytes fall back to Latin-1 rather
    than being rejected or replaced, and the value keeps its `kind` so a caller can see which rule
    produced it.
    """
    cases = {
        12: (b"Example", "Example", "utf8String"),
        18: (b"123", "123", "numericString"),
        19: (b"Example", "Example", "printableString"),
        20: (b"Caf\xe9", "Café", "teletexString"),  # not valid UTF-8: Latin-1 fallback
        22: (b"example.com", "example.com", "ia5String"),
        26: (b"Visible", "Visible", "visibleString"),
        27: (b"General", "General", "generalString"),
        28: ("Uni".encode("utf-32-be"), "Uni", "universalString"),
        30: ("Bmp".encode("utf-16-be"), "Bmp", "bmpString"),
    }
    for tag, (content, expected, kind) in cases.items():
        ava = _tlv(0x30, _OID_2_5_4_6 + _tlv(tag, content))
        node, _ = decode(_tlv(0x30, _tlv(0x31, ava)))
        parsed = parse_name(node)
        assert parsed.rfc4514() == f"C={expected}", hex(tag)
        assert parsed.rdnsets[0][0].kind == kind, hex(tag)


def test_tags_the_old_table_claimed_as_string_types_are_refused_by_number() -> None:
    """Regression witness for the numbering defect, stated as the refusal it has to be.

    X.680 (02/2021) Table 1 assigns universal 13 to the Relative object identifier type and 14 to the TIME
    type. `name.py` used to call those two numericString and printableString, so an attribute value spelled
    with either tag was read as a name without complaint. Nothing in the trust store exercises either tag -
    zero occurrences in 75 certificates - which is precisely why the wrong table survived: no real document
    was there to contradict it. This test is the witness that fails if the entries come back.
    """
    for tag in (13, 14):
        ava = _tlv(0x30, _OID_2_5_4_6 + _tlv(tag, b"US"))
        node, _ = decode(_tlv(0x30, _tlv(0x31, ava)))
        with pytest.raises(CertificateError, match="not a string type"):
            parse_name(node)


def test_a_string_type_this_codec_does_not_model_is_refused_by_name() -> None:
    """An unmodelled character string type must not be read through a guessed codec.

    Tag 21 sits inside the 18-22 band that X.680 Table 1 labels character string types, but this codec has
    no entry for it, because the number could not be re-read from the text this session and inventing one is
    how the table broke. The refusal therefore has to distinguish "a string type I decline" from "not a
    string type": the second would be a false statement about the bytes, and a caller that trusts a name it
    could not actually read is the failure this package exists to prevent.
    """
    ava = _tlv(0x30, _OID_2_5_4_6 + _tlv(21, b"Videotex"))
    node, _ = decode(_tlv(0x30, _tlv(0x31, ava)))
    with pytest.raises(CertificateError, match="does not model"):
        parse_name(node)


def test_encoding_order_is_root_first_and_the_string_form_reverses_it() -> None:
    """`within` depends on which end is the root, so the order is pinned from both sides."""
    der = (FIXTURES / "multivalue-rdn.der").read_bytes()
    dn = subject(der)
    assert dn.rfc4514().endswith("C=FR+O=Example  Université  S.A."), "rendering reverses"
    assert "pki@example.test" not in dn.rfc4514().split(",")[1], "leaf first in the string"

    anchor = Name(rdnsets=dn.rdnsets[:1], raw=b"")
    assert within(dn, anchor), "a name is within its own root"
    assert not within(anchor, dn), "a root is not within a name longer than itself"
    assert within(dn, dn), "matching counts as within: §7.1 allows equal length"


@pytest.mark.parametrize(
    ("stored", "prepared"),
    [
        ("foo bar  ", " foo  bar "),  # RFC 4518 §2.6.1's own worked example
        ("Paris", " paris "),
        ("  Paris  ", " paris "),
        ("PARIS", " paris "),
        ("paris  paris", " paris  paris "),  # one inner space becomes two
        ("", "  "),  # no non-space character: exactly two SPACEs
        ("   ", "  "),
        ("a\u00a0\u00a0b", " a  b "),  # NO-BREAK SPACE is a space for these purposes
        ("soft\u00adhyphen", " softhyphen "),  # soft hyphen maps away
        ("e\u0301", " \u00e9 "),  # NFD composes to NFC before comparison
        ("E\u0301", " \u00e9 "),
    ],
)
def test_insignificant_space_handling_is_the_rule_the_rfc_states_not_the_intuitive_one(
    stored: str, prepared: str
) -> None:
    """§2.6.1 adds a leading and trailing SPACE instead of trimming them.

    It reads like a bug and is not one: putting exactly one space at each end and collapsing every
    inner run to two is what makes `"Paris"`, `" paris "` and `"  PARIS  "` compare equal while
    still distinguishing nothing about inner runs. An implementation that trims instead produces a
    different equality relation than every directory doing this correctly.
    """
    assert normalize_value(stored) == prepared, repr(stored)
    assert normalize_value(prepared) == prepared, "and it is stable under repetition"


def _rdn(*pairs: tuple[tuple[int, ...], str]) -> tuple[Attribute, ...]:
    return tuple(Attribute(oid=oid, value=value, kind="utf8String") for oid, value in pairs)


def _dn(*rdnsets: tuple[Attribute, ...]) -> Name:
    """A Name built in memory. `raw` is empty because these cases test matching, not parsing."""
    return Name(rdnsets=rdnsets, raw=b"")


CN = (2, 5, 4, 3)
C = (2, 5, 4, 6)
ORG = (2, 5, 4, 10)


def test_equality_follows_the_matching_rules_in_order() -> None:
    """Same types, prepared values, same RDN count, same order; attributes may pair any which way."""
    left = _dn(_rdn((C, "US")), _rdn((ORG, "Example Corp.")))
    assert names_equal(left, _dn(_rdn((C, " us ")), _rdn((ORG, "example corp."))))
    assert not names_equal(left, _dn(_rdn((ORG, "Example Corp.")), _rdn((C, "US"))))  # order
    assert not names_equal(left, _dn(_rdn((C, "US"))))  # fewer RDNs
    assert not names_equal(_dn(_rdn((C, "US"))), _dn(_rdn((ORG, "US"))))  # same value, other type
    assert not names_equal(_dn(_rdn((C, "US"), (ORG, "X"))), _dn(_rdn((C, "US"))))  # arity
    assert names_equal(_dn(_rdn((C, "US"), (ORG, "X"))), _dn(_rdn((ORG, "x"), (C, "us"))))
    # Two attributes of one type in one RDN: pairing must not reuse the same candidate.
    assert not names_equal(_dn(_rdn((C, "US"), (C, "FR"))), _dn(_rdn((C, "US"), (C, "US"))))


@pytest.mark.parametrize(
    ("value", "rendered"),
    [
        ("#1", "\\#1"),  # SHARP only at the start
        ("a#b", "a#b"),
        ("DigiCert, Inc.", "DigiCert\\, Inc."),
        ("x ", "x\\ "),  # trailing SPACE
        (" x", "\\ x"),  # leading SPACE
        ('q"t', 'q\\"t'),
        ("a+b;c<d>e\\f", "a\\+b\\;c\\<d\\>e\\\\f"),
        ("\x01abc", "\\01abc"),
        ("\x7f", "\\7f"),
        ("", ""),
    ],
)
def test_escaping_follows_rfc_4514_which_characters_are_special_where(
    value: str, rendered: str
) -> None:
    assert _dn(_rdn((CN, value))).rfc4514() == f"CN={rendered}", repr(value)


def test_name_equality_ignores_the_encoding_and_the_bytes() -> None:
    """`==` on a Name means §7.1 match: neither the string type nor the stored bytes decide it.

    The same name legitimately appears as `C=US` in PrintableString in one document and `C=us` in
    UTF8String in another. A dataclass comparison - which would include `kind` and `raw` - calls
    those two different names, and a name pinned for trust would stop matching.

    The reverse trap is worth measuring too: in a self-signed certificate the issuer and subject
    TLVs are byte-identical, so comparing bytes would report "same name" here for a reason that
    has nothing to do with names matching. Both assertions are pinned below.
    """

    def name_with(tag: int, content: bytes) -> Name:
        ava = _tlv(0x30, _OID_2_5_4_6 + _tlv(tag, content))
        node, _ = decode(_tlv(0x30, _tlv(0x31, ava)))
        return parse_name(node)

    printable = name_with(19, b"US")
    utf8_lower = name_with(12, b"us")
    assert printable == utf8_lower, "different types, different case, one name"
    assert printable.raw != utf8_lower.raw
    assert len({printable, utf8_lower}) == 1, "hash follows equality"
    assert not names_equal(printable, name_with(12, b"GB"))

    der = (FIXTURES / "root-ecdsa.der").read_bytes()
    subject_dn, issuer_dn = subject(der), issuer(der)
    assert subject_dn.raw == issuer_dn.raw, "self-signed: the two TLVs are identical bytes"
    assert subject_dn == issuer_dn
    swapped = Name(rdnsets=tuple(reversed(subject_dn.rdnsets)), raw=b"")
    assert swapped != subject_dn, "RDN order is significant"
    assert len({swapped, subject_dn}) == 2

    multi = subject((FIXTURES / "multivalue-rdn.der").read_bytes())
    assert len(multi.rdnsets[0]) > 1, "the fixture must really be multi-valued for this to test"
    reversed_root = Name(rdnsets=(tuple(reversed(multi.rdnsets[0])),), raw=b"")
    root = Name(rdnsets=multi.rdnsets[:1], raw=b"")
    assert reversed_root == root, "attribute order inside an RDN is not"
    assert len({reversed_root, root}) == 1


def test_unknown_attribute_types_survive_as_dotted_oids() -> None:
    """Nothing is dropped on the way out: an unrecognised type still names the same attribute."""
    weird = (1, 2, 3, 4)
    assert _dn(_rdn((weird, "value"))).rfc4514() == "1.2.3.4=value"


def _tlv(tag: int, content: bytes) -> bytes:
    return bytes([tag, len(content)]) + content


_OID_2_5_4_6 = _tlv(0x06, bytes.fromhex("550406"))  # countryName


@pytest.mark.parametrize(
    ("label", "raw"),
    [
        ("not a SEQUENCE at all", _tlv(0x02, b"\x01")),
        ("an RDN that is not a SET", _tlv(0x30, _tlv(0x02, b"\x01"))),
        ("an empty RDN", _tlv(0x30, _tlv(0x31, b""))),
        (
            "an attribute value that is not a string type",
            _tlv(0x30, _tlv(0x31, _tlv(0x30, _OID_2_5_4_6 + _tlv(0x04, b"\x05")))),
        ),
        (
            "a UTF8String that is not valid UTF-8",
            _tlv(0x30, _tlv(0x31, _tlv(0x30, _OID_2_5_4_6 + _tlv(0x0C, b"\xff\xfe")))),
        ),
        (
            "an AttributeTypeAndValue with one field",
            _tlv(0x30, _tlv(0x31, _tlv(0x30, _OID_2_5_4_6))),
        ),
    ],
)
def test_names_that_are_not_names_are_refused(label: str, raw: bytes) -> None:
    node, _ = decode(raw)
    with pytest.raises(CertificateError, match=r"[A-Za-z]"):
        parse_name(node)
    assert label
